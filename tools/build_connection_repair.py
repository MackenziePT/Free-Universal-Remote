"""Build a self-contained Windows repair for the known RC4 verifier defect."""
import argparse
import base64
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OLD_HASHES = [
    '5230f185d1c12e638d3643c8068938e70d2e2bb44d21019090ac04844e72db31',
    '437e89b49fe0ace8565f070e52f64090dca3d379c686e2b55a036e7d631aba28',
]
HEADER = r'''@echo off
setlocal DisableDelayedExpansion
title Universal Remote MCP - reparar e ligar
set "URM_REPAIR_SELF=%~f0"
set "URM_REPAIR_MODE=%~1"
set "URM_REPAIR_PS=%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe"
if exist "%SystemRoot%\Sysnative\WindowsPowerShell\v1.0\powershell.exe" set "URM_REPAIR_PS=%SystemRoot%\Sysnative\WindowsPowerShell\v1.0\powershell.exe"
echo Universal Remote MCP - reparacao do verificador
echo A chave, se necessaria, sera pedida apenas na janela protegida.
echo Nunca envie a chave para a conversa.
"%URM_REPAIR_PS%" -NoLogo -NoProfile -ExecutionPolicy Bypass -Command "$s=[IO.File]::ReadAllText($env:URM_REPAIR_SELF); $m=[Environment]::NewLine+'# UNIVERSAL_REMOTE_REPAIR_PAYLOAD'+[Environment]::NewLine; $i=$s.IndexOf($m,[StringComparison]::Ordinal); if($i -lt 0){throw 'Repair payload missing'}; & ([ScriptBlock]::Create($s.Substring($i+$m.Length)))"
set "URM_REPAIR_RESULT=%ERRORLEVEL%"
echo.
if not "%URM_REPAIR_RESULT%"=="0" echo A etapa indicada acima precisa de diagnostico. Nao envie credenciais.
echo Prima uma tecla para fechar esta janela.
pause >nul
exit /b %URM_REPAIR_RESULT%
# UNIVERSAL_REMOTE_REPAIR_PAYLOAD
'''
BODY = r'''# Generated by tools/build_connection_repair.py. No credentials are embedded.
function Invoke-UniversalVerifierRepair {
    [CmdletBinding()]
    param([Parameter(Mandatory=$true)][string]$State, [switch]$Rollback)
    $ErrorActionPreference = 'Stop'
    if (-not [IO.Path]::IsPathRooted($State)) { throw 'State path must be absolute.' }
    $App = Join-Path $State 'app'
    $Target = Join-Path $App 'scripts\Verify-Windows.ps1'
    $Backup = Join-Path $State 'repair-backups\verify-cwd-20261022\Verify-Windows.ps1.bak'
    $OldHashes = @(__OLD_HASHES__)
    $FixedBytes = [Convert]::FromBase64String('__FIXED_BYTES__')
    $FixedHash = '__FIXED_HASH__'
    if (-not (Test-Path -LiteralPath $Target -PathType Leaf)) {
        throw 'Installed RC4 verifier not found. Extract the full release and run INICIAR.cmd.'
    }
    if (-not (Test-Path -LiteralPath (Join-Path $App 'scripts\Bootstrap.ps1') -PathType Leaf)) {
        throw 'Installed bootstrap not found. No file changed.'
    }
    $Mutex = [Threading.Mutex]::new($false, 'Local\HarmonyRemoteMCP')
    $Locked = $false
    $Temp = $null
    try {
        try { $Locked = $Mutex.WaitOne(0) }
        catch [Threading.AbandonedMutexException] { $Locked = $true }
        if (-not $Locked) { throw 'Stop the active tunnel with Stop-Tunnel.ps1 before repairing.' }
        $CurrentHash = (Get-FileHash -LiteralPath $Target -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($Rollback) {
            if (-not (Test-Path -LiteralPath $Backup -PathType Leaf)) { throw 'No repair backup available.' }
            $BackupHash = (Get-FileHash -LiteralPath $Backup -Algorithm SHA256).Hash.ToLowerInvariant()
            if ($BackupHash -notin $OldHashes) { throw 'Backup integrity mismatch. No file changed.' }
            if ($CurrentHash -eq $BackupHash) { Write-Host 'Previous verifier already restored.'; return $App }
            if ($CurrentHash -ne $FixedHash) { throw 'Verifier changed after repair. Refusing to overwrite it.' }
            $Bytes = [IO.File]::ReadAllBytes($Backup)
            $ExpectedHash = $BackupHash
        } else {
            if ($CurrentHash -eq $FixedHash) { Write-Host 'Verifier correction already installed.'; return $App }
            if ($CurrentHash -notin $OldHashes) { throw 'Unknown verifier revision. No file changed; use the full release.' }
            $Tokens = $null; $ParseErrors = $null
            $null = [Management.Automation.Language.Parser]::ParseInput([Text.Encoding]::UTF8.GetString($FixedBytes), [ref]$Tokens, [ref]$ParseErrors)
            if ($ParseErrors.Count -ne 0) { throw 'Invalid correction payload. No file changed.' }
            $BackupDirectory = [IO.Path]::GetDirectoryName($Backup)
            $null = [IO.Directory]::CreateDirectory($BackupDirectory)
            if (-not (Test-Path -LiteralPath $Backup -PathType Leaf)) {
                [IO.File]::Copy($Target, $Backup, $false)
            }
            $BackupHash = (Get-FileHash -LiteralPath $Backup -Algorithm SHA256).Hash.ToLowerInvariant()
            if ($BackupHash -ne $CurrentHash) { throw 'Existing backup differs from current verifier. No file changed.' }
            $Bytes = $FixedBytes
            $ExpectedHash = $FixedHash
        }
        $Temp = $Target + '.repair.' + [Guid]::NewGuid().ToString('N')
        [IO.File]::WriteAllBytes($Temp, $Bytes)
        if ((Get-FileHash -LiteralPath $Temp -Algorithm SHA256).Hash.ToLowerInvariant() -ne $ExpectedHash) {
            throw 'Correction integrity check failed. Original verifier retained.'
        }
        if ((Get-FileHash -LiteralPath $Target -Algorithm SHA256).Hash.ToLowerInvariant() -ne $CurrentHash) {
            throw 'Verifier changed during repair. Original file retained.'
        }
        [IO.File]::Replace($Temp, $Target, [NullString]::Value)
        $Temp = $null
        if ((Get-FileHash -LiteralPath $Target -Algorithm SHA256).Hash.ToLowerInvariant() -ne $ExpectedHash) {
            throw 'Final verifier hash mismatch. Use the retained backup for recovery.'
        }
        if ($Rollback) { Write-Host 'Previous verifier restored; tunnel setup was not started.' }
        else { Write-Host 'Verifier corrected. All regression and MCP checks remain enabled.' }
        Write-Host ('Backup: ' + $Backup)
        return $App
    } finally {
        if ($Temp -and (Test-Path -LiteralPath $Temp)) { Remove-Item -LiteralPath $Temp -Force }
        if ($Locked) { $Mutex.ReleaseMutex() }
        $Mutex.Dispose()
    }
}

if ($MyInvocation.InvocationName -ne '.') {
    $ErrorActionPreference = 'Stop'
    try {
        if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) { throw 'Run this repair on the Windows PC.' }
        if ([string]::IsNullOrWhiteSpace($env:LOCALAPPDATA)) { throw 'LOCALAPPDATA is unavailable.' }
        if ($env:URM_REPAIR_MODE -and $env:URM_REPAIR_MODE -ne '--rollback') { throw 'Use no argument, or --rollback.' }
        $Rollback = $env:URM_REPAIR_MODE -eq '--rollback'
        $State = Join-Path $env:LOCALAPPDATA 'HarmonyRemoteMCP'
        $App = Invoke-UniversalVerifierRepair -State $State -Rollback:$Rollback
        if (-not $Rollback) {
            $Arguments = @{EnableStartup=$true}
            if (-not (Test-Path -LiteralPath (Join-Path $State 'tunnel-key.dpapi') -PathType Leaf)) {
                $Arguments.TunnelId = '__TUNNEL_ID__'
            }
            & (Join-Path $App 'scripts\Bootstrap.ps1') @Arguments
        }
        exit 0
    } catch {
        Write-Host $_.Exception.Message -ForegroundColor Red
        Write-Host 'Send only the error or bootstrap-status.json; never the API key.'
        exit 1
    }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tunnel-id', default='', help='Optional non-secret ID for a personal repair launcher')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.tunnel_id and not re.fullmatch(r'tunnel_[0-9a-f]{32}', args.tunnel_id):
        parser.error('Invalid tunnel ID')
    fixed = (ROOT/'scripts/Verify-Windows.ps1').read_bytes()
    body = BODY.replace('__OLD_HASHES__', ','.join(repr(x) for x in OLD_HASHES))
    body = body.replace('__FIXED_BYTES__', base64.b64encode(fixed).decode('ascii'))
    body = body.replace('__FIXED_HASH__', hashlib.sha256(fixed).hexdigest())
    (ROOT/'scripts/Repair-Verification.ps1').write_text(body.replace('__TUNNEL_ID__', ''), encoding='ascii', newline='\n')
    out = args.output or ROOT/'CORRIGIR-E-LIGAR-UNIVERSAL-REMOTE.cmd'
    out.write_bytes((HEADER+body.replace('__TUNNEL_ID__', args.tunnel_id)).replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii'))
    print(out)


if __name__ == '__main__':
    main()
